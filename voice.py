# ---------------------------------------------------------------- تنظیمات / سطح
def _on():
    return B.get_setting("vc_on", "1") == "1" and B.get_setting("bot_enabled", "1") != "0"


def mode():
    return "public" if B.get_setting("vc_mode", "hide") == "public" else "hide"


def fallback_on():
    return B.get_setting("vc_fb", "1") == "1"


def _level(chat_id):
    now = time.time()
    with _lk:
        v = _lv.get(chat_id)
    if v is None:
        raw = B.get_setting(f"vc_lv_{chat_id}", "")
        try:
            lv, ts = raw.split(":")
            v = (int(lv), float(ts))
        except Exception:
            v = (0, 0.0)
        with _lk:
            _lv[chat_id] = v
    if v[0] and now - v[1] > LEVEL_TTL:
        return 0
    return v[0]


def _set_level(chat_id, lv):
    ts = time.time()
    with _lk:
        _lv[chat_id] = (lv, ts)
    try:
        B.set_setting(f"vc_lv_{chat_id}", f"{lv}:{int(ts)}")
    except Exception:
        logging.exception("vc set level")


def reset_levels():
    with _lk:
        _lv.clear()
    with B.get_db() as c:
        c.execute("DELETE FROM settings WHERE key LIKE 'vc_lv_%'")


def levels_count():
    with B.get_db() as c:
        return c.execute("SELECT COUNT(*) FROM settings WHERE key LIKE 'vc_lv_%' AND value NOT LIKE '0:%'").fetchone()[0]


