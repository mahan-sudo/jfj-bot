def on_group_message(message):
    try:
        user = message.get("from") or {}
        if not user or user.get("is_bot") or message.get("sender_chat") or message.get("via_bot"):
            return
        text = message.get("text") or message.get("caption") or ""
        if not text or text.startswith("/") or not has_jfj(text):
            return
        if not _on():
            logging.info("vc: جفج در گروه %s دیده شد ولی صدای جفج خاموش است", message["chat"]["id"])
            return
        logging.info("vc: جفج در گروه %s از کاربر %s دیده شد", message["chat"]["id"], user.get("id"))
        chat_id = message["chat"]["id"]
        uid = user["id"]
        now = time.time()
        with _lk:
            if now - _user_last.get((chat_id, uid), 0) < USER_COOLDOWN or now - _chat_last.get(chat_id, 0) < CHAT_COOLDOWN:
                return
            _user_last[(chat_id, uid)] = now
            _chat_last[chat_id] = now
            if len(_user_last) > 5000:
                for k in [k for k, v in _user_last.items() if now - v > USER_COOLDOWN]:
                    _user_last.pop(k, None)
        _pool.submit(_work, message, user, text)
    except Exception:
        logging.exception("vc on_group_message")


def _work(message, user, text):
    try:
        chat_id = message["chat"]["id"]
        r, m, lvl, kb = reply_to(chat_id, user, message["message_id"], text, message.get("message_thread_id"))
        if not r.get("ok"):
            logging.warning("vc: ارسال پاسخ ناموفق بود (گروه %s): %s", chat_id, _desc(r)[:200])
            return
        logging.info("vc: پاسخ ارسال شد (گروه %s، حالت %s)", chat_id, m)
        if m == "public":
            mid = (r.get("result") or {}).get("message_id")
            if mid:
                t = threading.Timer(VERIFY_AFTER, _verify, args=(chat_id, mid, kb, lvl))
                t.daemon = True
                t.start()
    except Exception:
        logging.exception("vc work")


