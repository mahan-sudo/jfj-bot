def _name(user):
    n = (user.get("first_name") or "").strip()
    n = re.sub(r"[^\w‌ ]", "", n)[:18].strip()
    return n or "عزیزم"


def render(cat, user, lvl, chat_id=0):
    pool = LINES.get(cat) or LINES["gen"]
    if cat != "gen" and random.random() < 0.2:
        pool = pool + LINES["gen"]
    last = _last_pick.get((chat_id, cat))
    cand = [x for x in pool if x != last] or pool
    raw = random.choice(cand)
    _last_pick[(chat_id, cat)] = raw
    clean = lvl >= 1
    s = "استارت" if clean else "/start"
    b = "ربات جفج" if clean else "@" + (B.BOT_USERNAME or "JFJImperialBot")
    return raw.replace("{S}", s).replace("{B}", b).replace("{n}", _name(user))


def keyboard():
    if not B.BOT_USERNAME:
        return None
    return {"inline_keyboard": [[{"text": random.choice(BTN_ALT), "style": B.DANGER,
                                  "url": f"https://t.me/{B.BOT_USERNAME}?start=jfj"}]]}


def _desc(r):
    return str((r or {}).get("description") or (r or {}).get("error_description") or "")


def _send(chat_id, user_id, mid, thread, text, kb, hide):
    p = {"chat_id": chat_id, "text": text}
    if kb:
        p["reply_markup"] = kb
    if hide:
        p["ephemeral_message_parameters"] = {"receiver_user_id": user_id}
        if thread:
            p["message_thread_id"] = thread
    else:
        p["reply_parameters"] = {"message_id": mid, "allow_sending_without_reply": True}
    return B.tg("sendMessage", **p)


def reply_to(chat_id, user, mid, text, thread=None, force_mode=None, force_level=None):
    """پاسخ را می‌فرستد. برمی‌گرداند (نتیجه، حالت واقعی، سطح، دکمه)"""
    uid = user["id"]
    lvl = _level(chat_id) if force_level is None else force_level
    m = force_mode or mode()
    cat = category(text)
    msg = render(cat, user, lvl, chat_id)
    kb = keyboard() if lvl < 2 else None
    hide = (m == "hide")
    r = _send(chat_id, uid, mid, thread, msg, kb, hide)
    if not r.get("ok") and kb and re.search(r"reply markup|button|BUTTON|URL", _desc(r)):
        kb = None                                   # تلگرام دکمه را نپذیرفت → بدون دکمه
        r = _send(chat_id, uid, mid, thread, msg, kb, hide)
    if not r.get("ok") and hide and fallback_on():
        logging.info("vc hide failed (%s) → public", _desc(r)[:120])
        hide = False
        r = _send(chat_id, uid, mid, thread, msg, kb, hide)
        if not r.get("ok") and kb and re.search(r"reply markup|button|BUTTON|URL", _desc(r)):
            kb = None
            r = _send(chat_id, uid, mid, thread, msg, kb, hide)
    return r, ("hide" if hide else "public"), lvl, kb


# ---------------------------------------------------------------- بررسی پاک شدن پیام
def _verify(chat_id, message_id, kb, used_level):
    try:
        p = {"chat_id": chat_id, "message_id": message_id}
        if kb:
            p["reply_markup"] = kb
        r = B.tg("editMessageReplyMarkup", **p)
        d = _desc(r)
        if r.get("ok") or "not modified" in d:
            return                                   # پیام هنوز هست
        if re.search(r"not found|MESSAGE_ID_INVALID", d, re.I):
            nl = min(max(used_level, _level(chat_id)) + 1, 2)
            _set_level(chat_id, nl)
            logging.warning("vc: پیام ربات در گروه %s پاک شد → سطح امن %s", chat_id, nl)
    except Exception:
        logging.exception("vc verify")


