def normalize(text):
    t = unicodedata.normalize("NFKC", text or "")
    t = t.replace("ي", "ی").replace("ى", "ی").replace("ك", "ک").replace("ە", "ه")
    t = _DIAC.sub("", t)
    return t


def has_jfj(text):
    """True اگر متن حاوی جفج (با هر سانسوری از لیست) باشد"""
    if not text:
        return False
    t = normalize(text)
    return bool(_FA.search(t) or _FA2.search(t) or _EN.search(t))


